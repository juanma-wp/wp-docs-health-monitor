import type { JoinResult, JoinedIssueFeedback } from './store.js';

// ---------------------------------------------------------------------------
// Calibration block generation — turns reviewed verdicts into the
// auto-managed section of a site-extension prompt (`prompts/<site>.md`).
//
// Layer rationale (CLAUDE.md "Where a new rule belongs"): TP/FP example
// lists earned from real reviews on a corpus are layer-4 material — the
// site extension. This module therefore only ever writes to the site
// extension, between explicit markers so hand-written rules survive
// regeneration. Patterns recurring across sites are NOT auto-promoted:
// `findPromotionCandidates` reports them for a human to move up the stack.
// ---------------------------------------------------------------------------

export const CALIBRATION_BEGIN = '<!-- BEGIN AUTO-CALIBRATION — generated by `npm run feedback -- apply`; edits inside this block are overwritten -->';
export const CALIBRATION_END   = '<!-- END AUTO-CALIBRATION -->';

export type RenderOptions = {
  // Cap per section, newest run first. Bounds prompt growth: the full
  // history stays in feedback/<site>/; the prompt carries the recent tail.
  maxPerSection?: number;
  // Truncation bound for quoted evidence inside the block.
  maxQuoteLength?: number;
};

const DEFAULT_MAX_PER_SECTION = 15;
const DEFAULT_MAX_QUOTE_LENGTH = 300;

function truncate(s: string, max: number): string {
  return s.length <= max ? s : `${s.slice(0, max - 1)}…`;
}

function quoteLine(label: string, value: string | undefined, max: number): string | null {
  if (!value) return null;
  return `  - ${label}: "${truncate(value.replace(/\s+/g, ' ').trim(), max)}"`;
}

function renderIssueEntry(entry: JoinedIssueFeedback, max: number): string {
  const { issue } = entry;
  const lines = [
    `- **${entry.slug}** (\`${issue.type}\`, ${issue.severity}, run ${entry.runId}; evidence \`${issue.evidence.codeRepo}:${issue.evidence.codeFile}\`)`,
    quoteLine('doc said', issue.evidence.docSays, max),
    quoteLine('code said', issue.evidence.codeSays, max),
    entry.notes ? `  - reviewer: ${entry.notes.trim()}` : null,
  ];
  return lines.filter((l): l is string => l !== null).join('\n');
}

// Newest runs first so the cap keeps the most recent learnings.
function newestFirst<T extends { runId: string }>(entries: T[]): T[] {
  return [...entries].sort((a, b) => b.runId.localeCompare(a.runId));
}

// Returns the markdown that goes BETWEEN the markers, or null when there is
// nothing decisive to teach (callers should not touch the prompt then).
export function renderCalibrationBlock(join: JoinResult, options: RenderOptions = {}): string | null {
  const maxPerSection = options.maxPerSection ?? DEFAULT_MAX_PER_SECTION;
  const maxQuote = options.maxQuoteLength ?? DEFAULT_MAX_QUOTE_LENGTH;

  const falsePositives = newestFirst(join.joined.filter(e => e.verdict === 'false-positive')).slice(0, maxPerSection);
  const exemplarTPs = newestFirst(join.joined.filter(e => e.verdict === 'true-positive' && e.exemplar)).slice(0, maxPerSection);
  const missed = newestFirst(join.missed).slice(0, maxPerSection);

  if (falsePositives.length === 0 && exemplarTPs.length === 0 && missed.length === 0) return null;

  const sections: string[] = [
    '### Learned calibration from review feedback',
    '',
    'The examples below come from human review verdicts on real runs of this corpus (see `feedback/`). They calibrate the generic rules above to observed failure modes — treat them with the same weight as the hand-written examples.',
  ];

  if (falsePositives.length > 0) {
    sections.push('', '#### Reviewer-rejected findings — do not report these again', '');
    sections.push(falsePositives.map(e => renderIssueEntry(e, maxQuote)).join('\n'));
  }

  if (exemplarTPs.length > 0) {
    sections.push('', '#### Reviewer-confirmed drift — exemplary findings to emulate', '');
    sections.push(exemplarTPs.map(e => renderIssueEntry(e, maxQuote)).join('\n'));
  }

  if (missed.length > 0) {
    sections.push('', '#### Known misses — drift a reviewer found that a run did not report', '');
    sections.push(missed.map(m => {
      const lines = [
        `- **${m.slug}** (run ${m.runId}): ${m.description.trim()}`,
        quoteLine('doc says', m.docSays, maxQuote),
        quoteLine('code says', m.codeSays, maxQuote),
        m.codeFile ? `  - evidence location: \`${m.codeRepo ? `${m.codeRepo}:` : ''}${m.codeFile}\`` : null,
      ];
      return lines.filter((l): l is string => l !== null).join('\n');
    }).join('\n'));
  }

  return sections.join('\n');
}

// Splices the block into the prompt text between the markers, idempotently.
// Hand-written content outside the markers is preserved byte-for-byte; a
// prompt without markers gets the managed region appended at the end.
export function spliceCalibration(existing: string, block: string): string {
  const region = `${CALIBRATION_BEGIN}\n\n${block}\n\n${CALIBRATION_END}`;
  const beginIdx = existing.indexOf(CALIBRATION_BEGIN);
  const endIdx = existing.indexOf(CALIBRATION_END);
  if (beginIdx !== -1 && endIdx !== -1 && endIdx > beginIdx) {
    const before = existing.slice(0, beginIdx);
    const after = existing.slice(endIdx + CALIBRATION_END.length);
    return `${before}${region}${after}`;
  }
  if (beginIdx !== -1 || endIdx !== -1) {
    throw new Error('Calibration markers are unbalanced in the existing prompt — fix the file by hand before re-running apply.');
  }
  const trimmed = existing.replace(/\s+$/, '');
  return trimmed.length > 0 ? `${trimmed}\n\n${region}\n` : `${region}\n`;
}

export type PromotionCandidate = {
  issueType: string;
  sites:     string[];
  fpCount:   number;
};

// A false-positive class recurring across sites is the CLAUDE.md signal to
// promote a rule up the layer stack (language pack / config / common
// prompt). That promotion is a judgement call, so this only REPORTS — the
// common prompt is never written by automation.
export function findPromotionCandidates(joinedBySite: Record<string, JoinedIssueFeedback[]>): PromotionCandidate[] {
  const byType = new Map<string, { sites: Set<string>; fpCount: number }>();
  for (const [site, entries] of Object.entries(joinedBySite)) {
    for (const entry of entries) {
      if (entry.verdict !== 'false-positive') continue;
      const agg = byType.get(entry.issue.type) ?? { sites: new Set<string>(), fpCount: 0 };
      agg.sites.add(site);
      agg.fpCount++;
      byType.set(entry.issue.type, agg);
    }
  }
  return [...byType.entries()]
    .filter(([, agg]) => agg.sites.size >= 2)
    .map(([issueType, agg]) => ({ issueType, sites: [...agg.sites].sort(), fpCount: agg.fpCount }))
    .sort((a, b) => b.fpCount - a.fpCount);
}
